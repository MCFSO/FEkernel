/* 按键事件（接口层）。
 *
 * ★ 为什么是"推送"而不是"拉取" ★
 *
 * 拉取式接口（客户端 call 一次拿一个事件）在本系统里有一个绕不开的问题：
 * 服务端要么**轮询**（烧 CPU、还有延迟），要么**挂起回复**（把回复端点留着，
 * 等有事件再回）。挂起回复本身没问题——控制台读一行就是这么做的——
 * 但按键服务同时还要**等 IRQ 通知**，而我们的 IPC 没有 select：
 * 一个线程没法同时"等中断"和"等请求"。
 * 那就要么给 kbd 加线程（IRQ 线程 + 服务线程 + 谁来唤醒谁），
 * 要么接受轮询。
 *
 * 推送式没有这个问题：**消费者创建端点，生产者往里发**。
 * kbd 保持单线程——等 IRQ → 解码 → 发出去，一步不差；
 * 控制台的输入线程阻塞在自己的端点上等事件，天然事件驱动、零轮询。
 *
 * 代价要说清楚：**这个端点只有一个消费者**（kbd 把事件推给"控制台的输入端点"，
 * 由控制台通过 devfs 发布）。要支持多个键盘消费者，就得在中间加一个
 * 真正的输入多路复用服务——那是将来的事，现在没有这个需求，
 * 而为不存在的需求造机制正是本项目一直在避免的。
 *
 * 这也解释了为什么键盘与块设备/文件系统的接口形态不同：
 * **块设备是"请求-应答"，按键是"事件流"**。形态跟着语义走，不是跟着习惯走。 */
#ifndef FE_KBD_H
#define FE_KBD_H

#include <fe_user.h>

/* 控制台的输入端点：kbd 通过 devfs 找到它，并把按键事件推给它。 */
#define FE_KBD_CONSOLE_IN_PATH "/dev/console_in"

/* 修饰键状态 */
#define FE_KBD_MOD_SHIFT 0x01
#define FE_KBD_MOD_CTRL  0x02
#define FE_KBD_MOD_ALT   0x04
#define FE_KBD_MOD_CAPS  0x08

/* 一个按键事件。载荷就是这个结构体本身（推送协议没有操作码——
 * 端点只传一种东西，"这是什么"由端点本身说清楚，比每条消息带一个 op 更省事）。 */
struct fe_kbd_event {
    u8 ascii;       /* 0 = 这个键没有可打印字符（功能键等） */
    u8 scancode;    /* set 1 的 make 码（已去掉 0x80 与 0xE0 前缀） */
    u8 pressed;     /* 1 = 按下，0 = 松开 */
    u8 mods;        /* FE_KBD_MOD_* */
    u8 extended;    /* 来自 0xE0 前缀（方向键、右 Ctrl 等） */
    u8 _pad[3];
};

#endif /* FE_KBD_H */
