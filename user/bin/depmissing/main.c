/* depmissing —— 依赖机制的**负向测试**：这个程序永远不该被运行。
 *
 * 它声明了一个硬依赖 `/dev/flaky0`，而那个名字由 `flaky` 提供——
 * 但 flaky 是个"启动就挂"的夹具，永远不会发布它。
 * 于是 init 必须在启动 depmissing 之前就把它跳过，并说明原因。
 *
 * 为什么值得专门造一个程序来测这件事：
 * 依赖机制**最容易错的就是失败路径**——正常路径（依赖都在）随便写写也能跑通，
 * 而"依赖没就绪"这条路上很容易退化成"照跑不误，然后在内部莫名其妙地失败"，
 * 那种失败现场离真正的原因隔着好几层。
 *
 * 所以：日志里出现下面这几行，就说明依赖机制失效了。
 */
#include <fe_user.h>

int main(void)
{
    fe_puts("\n!!! depmissing 竟然被运行了 —— 依赖机制失效 !!!\n");
    fe_puts("!!! 它声明的依赖 /dev/flaky0 由 flaky 提供，而 flaky 永不发布 !!!\n");
    fe_puts("!!! init 应当在启动它之前就跳过它                            !!!\n\n");
    return 99;      /* 非 0：让退出码校验也报出来 */
}
