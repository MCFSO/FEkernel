/* flaky —— 依赖机制的**负向测试夹具**：一个"启动就挂"的服务。
 *
 * 它被拉起之后只打一行日志说明自己的用途，然后**永远不发布它的名字**
 * （正常服务起来第一件事就是 fe_devfs_publish）。
 * 用来构造「依赖有提供者、但提供者没能就绪」这个运行期场景。
 *
 * 为什么不直接在单元表里写一个"没有提供者"的依赖来测：
 * 那是**静态配置错误**，init 的 preflight 在启动任何东西之前就会报出来，
 * 走的是另一条代码路径。真正容易写错、也真正会在生产里发生的是
 * 「服务启动时崩了，于是依赖它的东西该怎么办」——这条路径必须单独测。
 */
#include <fe_user.h>

int main(void)
{
    fe_puts("  [flaky] 我是负向测试夹具：不发布名字，用来验证依赖未就绪时的跳过逻辑\n");
    /* 活着但不发布 —— 让 init 的就绪等待走到超时分支 */
    for (;;) {
        fe_sleep_ms(1000);
    }
}
