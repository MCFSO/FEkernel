/* 机器复位（不返回）。
 *
 * 它属于 A/B 流程而不是"顺手的调试功能"：槽切换的唯一生效点是**重启**，
 * 所以"让机器重启"是这个系统必须具备的能力，否则更新写完只能靠人按电源键，
 * 回滚更是无从谈起。
 *
 * 为什么放 arch 层：复位是平台相关的一串 I/O 端口写，一点策略都没有。 */
#ifndef FE_RESET_H
#define FE_RESET_H

/* 复位机器。正常情况**永不返回**；三条路径都失败时停在这里（halt 循环），
 * 绝不返回给调用者——返回去会让调用者以为"重启完成了"，而其实没有。 */
void fe_machine_reset(void);

#endif /* FE_RESET_H */
