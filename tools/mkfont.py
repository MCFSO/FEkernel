def validate() -> list[str]:
    """返回问题列表。空列表 = 字形定义自洽。

    ★ 校验本身就是这个脚本存在的理由之一 ★
    直接把 95 张位图写进 C 文件也能跑，但"某一行少/多一个字符"这种错
    在位图里表现为"某个字符永远缺一角"，几乎不可能被人发现。
    在这里它是一条明确的错误信息。"""
    problems: list[str] = []
    want = [chr(c) for c in range(FIRST, LAST + 1)]
    for ch in want:
        if ch not in GLYPHS:
            problems.append(f"缺少字形: {ch!r} (0x{ord(ch):02x})")
            continue
        rows = GLYPHS[ch]
        if len(rows) != H:
            problems.append(f"{ch!r}: 行数 {len(rows)}，应为 {H}")
            continue
        for i, row in enumerate(rows):
            if len(row) != W:
                problems.append(f"{ch!r} 第 {i} 行宽度 {len(row)}，应为 {W}: {row!r}")
            bad = set(row) - {"#", " "}
            if bad:
                problems.append(f"{ch!r} 第 {i} 行有非法字符 {bad}")
    extra = set(GLYPHS) - set(want)
    if extra:
        problems.append(f"多余的字形定义: {sorted(extra)}")
    return problems


def glyph_bytes(rows: list[str]) -> list[int]:
    """7 行 → 8 字节（第 8 字节留空，让索引变成 char*8+row 的乘法）。"""
    out = []
    for row in rows:
        b = 0
        for x, c in enumerate(row):
            if c == "#":
                b |= 1 << x          # bit0 = 最左像素
        out.append(b)
    out.append(0)
    return out


def emit() -> str:
    lines = [
        "/* SPDX-License-Identifier: 0BSD */",
        "/* 由 tools/mkfont.py 生成，请勿手改。",
        " *",
        f" * 字形 {W}x{H}，放在 8 字节的槽里（第 8 字节留空），",
        " * bit0 = 最左像素。ASCII 32..126 共 95 个字形。",
        " *",
        " * 重新生成： python tools/mkfont.py",
        " * 校验定义： python tools/mkfont.py --check",
        " */",
        "#ifndef FE_CONSOLED_FONT5X7_H",
        "#define FE_CONSOLED_FONT5X7_H",
        "",
        f"#define FE_FONT_W     {W}",
        f"#define FE_FONT_H     {H}",
        f"#define FE_FONT_FIRST {FIRST}",
        f"#define FE_FONT_LAST  {LAST}",
        "#define FE_FONT_STRIDE 8",
        "",
        "static const unsigned char g_font5x7"
        f"[(FE_FONT_LAST - FE_FONT_FIRST + 1) * FE_FONT_STRIDE] = {{",
    ]
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        b = glyph_bytes(GLYPHS[ch])
        hexs = ", ".join(f"0x{v:02x}" for v in b)
        disp = ch if ch not in ("\\",) else "\\\\"
        lines.append(f"    {hexs},   /* {code:3d} {disp!r} */")
    lines += ["};", "", "#endif /* FE_CONSOLED_FONT5X7_H */", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description="生成控制台点阵字体")
    ap.add_argument("--check", action="store_true", help="只校验，不写文件")
    args = ap.parse_args()

    problems = validate()
    if problems:
        print("[mkfont] 字形定义有问题：", file=sys.stderr)
        for p in problems:
            print("   " + p, file=sys.stderr)
        return 1
    print(f"[mkfont] 字形定义自洽：ASCII {FIRST}..{LAST} 共 {LAST - FIRST + 1} 个，"
          f"每个 {W}x{H}")

    if args.check:
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(emit(), encoding="utf-8")
    print(f"[mkfont] 已生成 {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
